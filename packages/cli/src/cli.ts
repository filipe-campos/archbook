import { Command, InvalidArgumentError, Option } from "commander";
import pc from "picocolors";
import { buildCommand } from "./commands/build.js";
import type { CommandContext } from "./commands/context.js";
import { devCommand } from "./commands/dev.js";
import { generateCommand, generateExitCode } from "./commands/generate.js";
import { historyCommand } from "./commands/history.js";
import { initCommand } from "./commands/init.js";
import { removeCommand } from "./commands/remove.js";
import { snapshotCommand } from "./commands/snapshot.js";
import { undoCommand } from "./commands/undo.js";
import { validateCommand } from "./commands/validate.js";
import { SNAPSHOT_OPERATIONS } from "./core/history.js";
import { CancelledError, UserError } from "./errors.js";
import { plainOutput, terminalOutput } from "./io/output.js";
import { clackPrompter, defaultsPrompter, type Prompter } from "./io/prompter.js";
import { VERSION } from "./package.js";

const DEBUG_ENV = "ARCHBOOK_DEBUG";

function parsePort(value: string): number {
  const port = Number(value);
  if (!/^\d+$/.test(value) || port < 1 || port > 65535) {
    throw new InvalidArgumentError("Expected a whole number from 1 to 65535.");
  }
  return port;
}

const interactiveTerminal = () => Boolean(process.stdin.isTTY && process.stdout.isTTY);

function createContext(command: Command, overrides: { prompter?: Prompter } = {}): CommandContext {
  const interactive = interactiveTerminal();
  return {
    cwd: (command.optsWithGlobals() as { cwd?: string }).cwd ?? process.cwd(),
    interactive,
    prompter: overrides.prompter ?? (interactive ? clackPrompter : defaultsPrompter),
    // A live log needs only stdout to be a terminal, even when the questions cannot be asked.
    output: process.stdout.isTTY ? terminalOutput : plainOutput,
  };
}

export function createProgram(): Command {
  const program = new Command("archbook")
    .description("Living, replayable architecture docs, generated by Claude Code.")
    .version(VERSION, "-v, --version")
    .option("-C, --cwd <dir>", "project directory (default: the current directory)")
    .showHelpAfterError()
    .configureHelp({ sortSubcommands: false });

  let exitCode = 0;
  const run =
    (action: (command: Command) => number | Promise<number>) =>
    async (...args: unknown[]) => {
      exitCode = await action(args[args.length - 1] as Command);
    };

  program
    .command("init")
    .description("Set up Archbook: answer a few questions and install the Claude Code commands")
    .option("-y, --yes", "accept the defaults without asking")
    .option("--generate", "generate the docs right away (asked interactively otherwise)")
    .option("--no-generate", "do not generate the docs at the end")
    .action(
      run((command) => {
        const options = command.opts<{ yes?: boolean; generate?: boolean }>();
        const context = createContext(command, options.yes ? { prompter: defaultsPrompter } : {});
        return initCommand(options, context, async () =>
          generateExitCode(await generateCommand({}, context)),
        );
      }),
    );

  program
    .command("generate")
    .description("Generate archbook/architecture.json with Claude Code (headless)")
    .option("-m, --model <model>", "Claude model to use, e.g. sonnet or opus")
    .option("--verbose", "show more of Claude's progress")
    .action(
      run(async (command) =>
        generateExitCode(await generateCommand(command.opts(), createContext(command))),
      ),
    );

  program
    .command("dev")
    .description("Serve the viewer with live reload")
    .option("-p, --port <port>", "port", parsePort, 4400)
    .option("--host <host>", "host to bind", "localhost")
    .option("-o, --open", "open the browser")
    .action(run((command) => devCommand(command.opts(), createContext(command))));

  program
    .command("build")
    .description("Build a static site (viewer + architecture.json), e.g. for GitHub Pages")
    .option("--out <dir>", "output folder (default: archbook/dist)")
    .action(run((command) => buildCommand(command.opts(), createContext(command))));

  program
    .command("validate")
    .description("Check architecture.json against the schema and the code on disk")
    .option("--json", "machine-readable output")
    .option("--file <path>", "validate another file instead of archbook/architecture.json")
    .action(run((command) => validateCommand(command.opts(), createContext(command))));

  program
    .command("history")
    .description("List saved snapshots of architecture.json and what each operation changed")
    .option("--json", "machine-readable output")
    .action(run((command) => historyCommand(command.opts(), createContext(command))));

  program
    .command("undo")
    .description("Restore the previous architecture.json (run again to redo)")
    .option("--to <id>", "restore a specific snapshot (see archbook history)")
    .action(run((command) => undoCommand(command.opts(), createContext(command))));

  program
    .command("remove")
    .description("Remove Archbook from this project, using the install manifest")
    .option("--keep-docs", "keep archbook/architecture.json and the build; remove everything else")
    .option("--dry-run", "only list what would be removed")
    .option("-y, --yes", "do not ask for confirmation (edited files are kept)")
    .action(run((command) => removeCommand(command.opts(), createContext(command))));

  program
    .command("snapshot", { hidden: true })
    .description(
      "Save architecture.json before an operation changes it (used by the Claude Code commands)",
    )
    .addOption(
      new Option("--op <operation>", "operation name")
        .choices(SNAPSHOT_OPERATIONS)
        .makeOptionMandatory(),
    )
    .action(run((command) => snapshotCommand(command.opts(), createContext(command))));

  program.hook("postAction", () => {
    process.exitCode = exitCode;
  });
  return program;
}

export async function main(argv = process.argv): Promise<void> {
  try {
    await createProgram().parseAsync(argv);
  } catch (error) {
    if (error instanceof CancelledError) {
      console.error(pc.yellow("Cancelled."));
      process.exitCode = 130;
    } else if (error instanceof UserError) {
      console.error(`${pc.red("✖")} ${error.message}`);
      process.exitCode = error.exitCode;
    } else {
      const message = error instanceof Error ? error.message : String(error);
      console.error(`${pc.red("✖")} Unexpected error: ${message}`);
      if (process.env[DEBUG_ENV] === "1") console.error(error);
      else console.error(pc.dim(`Set ${DEBUG_ENV}=1 to see the stack trace.`));
      process.exitCode = 1;
    }
  }
}
